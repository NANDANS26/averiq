"""005 - policy, interventions, human reviews

Revision ID: e5f6a1b2c3d4
Revises: d4e5f6a1b2c3
Create Date: 2024-01-01 00:00:00.000000

Creates the three tables that govern the Policy_Engine and human-in-the-loop
review workflow:

- policies      — versioned policy configurations per merchant; only one may
                  be 'active' at any time (partial UNIQUE index enforces this).
- interventions — recovery action candidates generated by the Intervention
                  Engine; each is scored, ranked, and evaluated by the
                  Policy_Engine before execution.
- human_reviews — open/assigned/resolved review queue; OPERATOR+ actors
                  approve or reject flagged interventions.

Key design decisions
--------------------
* policies.lifecycle_state uses a VARCHAR CHECK constraint (not a PostgreSQL
  ENUM) so adding states requires only a CHECK constraint change, not a full
  table rewrite.
* The partial UNIQUE index idx_policies_active guarantees at-most-one active
  policy per merchant at the DB level. The application layer retires the
  previous active version atomically before activating a new one.
* interventions.policy_version_id is a hard FK to the policies row whose
  rules produced this intervention — ensures every intervention is traceable
  to the exact policy snapshot that evaluated it.
* intervention_type and execution_capability are CHECK-constrained to the
  canonical enum values from the shared/contracts/ module.

Requirements: FR-POLICY-012, FR-POLICY-013
"""

