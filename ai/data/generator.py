"""Synthetic data generator for Averiq's ML training pipeline.

Produces realistic payment failure cases with no label leakage between features
and recovery outcomes.

Latent behaviour model (documented per EVAL-007, DOC-003):

  1. Each synthetic customer has a latent ``creditworthiness_score`` drawn from
     a Beta(2, 5) distribution (seeded, reproducible).  Higher scores indicate
     more reliable payers.

  2. ``failure_category`` is drawn from a mixture distribution whose weights are
     modulated by creditworthiness:
       - Customers with low creditworthiness have higher probability of
         INSUFFICIENT_FUNDS / CARD_DECLINED.
       - Customers with high creditworthiness have higher probability of
         TECHNICAL_FAILURE / NETWORK_TIMEOUT (transient, recoverable).

  3. Each observable feature is derived deterministically from the latent
     variables and from independent random draws (not from the outcome).

  4. ``recovery_outcome = Bernoulli(intervention_response_probability)`` where
     ``intervention_response_probability`` is a function of the failure
     category and customer history — computed AFTER features, via a separate
     independent random draw.  No feature column encodes the outcome directly.

Label leakage prevention (EVAL-008):
  The target ``recovery_outcome`` is generated by a separate RNG call that
  consumes only latent variables and a final draw; it is never used as input to
  any feature column.

Temporal structure (EVAL-009):
  Cases are assigned synthetic ``created_at`` timestamps spread over a
  configurable date range, ordered chronologically so that the temporal split
  in ``feature_extraction.py`` is meaningful.

Requirements: EVAL-005, EVAL-006, EVAL-007, EVAL-008, EVAL-010
"""

from __future__ import annotations

import random
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone
from typing import Final

# ---------------------------------------------------------------------------
# Configurable constants (documented assumptions)
# ---------------------------------------------------------------------------

#: Synthetic data time range — cases span this many days before the epoch.
_DATA_HORIZON_DAYS: Final[int] = 365

#: Epoch (latest possible created_at)
_EPOCH: Final[datetime] = datetime(2024, 1, 1, 0, 0, 0, tzinfo=timezone.utc)

#: Number of distinct synthetic merchants
_NUM_MERCHANTS: Final[int] = 10

#: Number of synthetic customers per merchant
_CUSTOMERS_PER_MERCHANT: Final[int] = 200

#: Base recovery rates by failure category (intervention response probability)
#: These rates capture realistic domain knowledge about which failures are recoverable.
#: Documented as part of the latent behaviour model — not hardcoded targets.
_BASE_RECOVERY_RATE: Final[dict[str, float]] = {
    "INSUFFICIENT_FUNDS": 0.15,        # Low — customer may not be able to pay
    "CARD_DECLINED": 0.35,             # Moderate — often transient bank decisions
    "EXPIRED_CARD": 0.55,              # Moderate-high — customer can update card
    "AUTHENTICATION_FAILURE": 0.60,    # High — abandoned auth can be retried
    "TECHNICAL_FAILURE": 0.70,         # High — transient, often self-resolving
    "NETWORK_TIMEOUT": 0.65,           # High — transient network issue
    "FRAUD_SUSPECTED": 0.10,           # Very low — requires manual review
    "LIMIT_EXCEEDED": 0.40,            # Moderate — limit may reset or customer retries
    "UNKNOWN": 0.25,                   # Below average — uncertain root cause
}

#: Failure category distribution weights (base, before creditworthiness adjustment)
_FAILURE_WEIGHTS: Final[dict[str, float]] = {
    "INSUFFICIENT_FUNDS": 0.25,
    "CARD_DECLINED": 0.20,
    "EXPIRED_CARD": 0.10,
    "AUTHENTICATION_FAILURE": 0.15,
    "TECHNICAL_FAILURE": 0.12,
    "NETWORK_TIMEOUT": 0.08,
    "FRAUD_SUSPECTED": 0.04,
    "LIMIT_EXCEEDED": 0.04,
    "UNKNOWN": 0.02,
}

#: Payment methods and their relative frequency
_PAYMENT_METHODS: Final[list[tuple[str, float]]] = [
    ("card", 0.55),
    ("upi", 0.25),
    ("netbanking", 0.12),
    ("wallet", 0.05),
    ("emi", 0.03),
]

#: Exposure tier thresholds in paise (INR minor units)
#: HIGH ≥ 100 000 paise (₹1 000), MEDIUM ≥ 20 000 paise (₹200), else LOW
_EXPOSURE_HIGH_PAISE: Final[int] = 100_000
_EXPOSURE_MEDIUM_PAISE: Final[int] = 20_000


# ---------------------------------------------------------------------------
# SyntheticCase dataclass
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class SyntheticCase:
    """A single synthetic payment failure case.

    All fields are deterministic given the same seed.  No field encodes the
    ``recovery_outcome`` directly — see module docstring for the leakage
    prevention guarantee.

    This is a pure data container used by the training pipeline; it is NOT
    a SQLAlchemy model.
    """

    # ---- Identifiers ----
    case_id: str
    merchant_id: str
    customer_id: str
    payment_id: str

    # ---- Temporal ----
    created_at: datetime  # UTC, timezone-aware

    # ---- Payment features (model inputs) ----
    amount_paise: int                   # integer minor units, never float
    currency: str                       # ISO 4217 (always "INR" for MVP)
    failure_category: str               # one of the 9 FailureCategory values
    payment_method: str
    payment_attempt_count: int          # number of prior attempts
    successful_payment_count: int       # number of prior successes
    hour_of_day: int                    # 0–23
    day_of_week: int                    # 0=Monday, 6=Sunday
    has_subscription: bool

    # ---- Exposure tier (deterministic from amount) ----
    exposure_tier: str                  # HIGH | MEDIUM | LOW

    # ---- Target label ----
    recovery_outcome: bool              # True = recovered; generated AFTER features


# ---------------------------------------------------------------------------
# Generator implementation
# ---------------------------------------------------------------------------


class SyntheticDataGenerator:
    """Generate reproducible synthetic payment failure cases.

    Usage::

        cases = SyntheticDataGenerator().generate(seed=42, count=50_000)

    Calling ``generate(seed=42, count=50_000)`` twice returns identical
    results (Property 12 guarantee, EVAL-006).

    The generator supports any ``count >= 1``; the recommended production
    range is 50 000–250 000.  Small counts (100–1 000) are valid for smoke
    tests (see EVAL-005 note in task 10.1).
    """

    def generate(self, seed: int, count: int) -> list[SyntheticCase]:
        """Generate ``count`` synthetic payment failure cases.

        Parameters
        ----------
        seed:
            Random seed for full reproducibility.  Given the same seed and
            count, the output is identical across invocations.
        count:
            Number of cases to generate (must be >= 1).

        Returns
        -------
        list[SyntheticCase]
            Cases ordered chronologically by ``created_at`` (oldest first).
            Ordering is stable for the same seed.

        Notes
        -----
        * All amounts are integers in paise (INR minor units).
        * No feature column encodes ``recovery_outcome`` — see module docstring.
        * Temporal spread: ``created_at`` values span the 365 days before
          ``_EPOCH`` (2024-01-01 UTC) so that the temporal split in
          ``feature_extraction.py`` produces meaningful non-overlapping splits.
        """
        if count < 1:
            msg = f"count must be >= 1, got {count}"
            raise ValueError(msg)

        # Seed the master RNG — all downstream draws derive from this.
        rng = random.Random(seed)  # noqa: S311  (not used for cryptography)

        # -------------------------------------------------------------------
        # 1. Materialise latent customer profiles (seeded once, globally)
        # -------------------------------------------------------------------
        customers = self._generate_customers(rng)

        # -------------------------------------------------------------------
        # 2. Generate one case per index
        # -------------------------------------------------------------------
        cases: list[SyntheticCase] = []
        for i in range(count):
            case = self._generate_case(i, rng, customers)
            cases.append(case)

        # -------------------------------------------------------------------
        # 3. Sort by created_at (oldest first) for temporal integrity
        # -------------------------------------------------------------------
        cases.sort(key=lambda c: c.created_at)

        return cases

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _generate_customers(
        self, rng: random.Random
    ) -> list[dict[str, object]]:
        """Materialise a fixed pool of synthetic customers."""
        customers = []
        for merchant_idx in range(_NUM_MERCHANTS):
            merchant_id = f"merch_{merchant_idx:03d}"
            for cust_idx in range(_CUSTOMERS_PER_MERCHANT):
                # Latent creditworthiness from Beta(2, 5): skewed low
                # (most customers have moderate-to-low creditworthiness)
                alpha, beta = 2.0, 5.0
                # Approximate Beta using ratio of Gamma random variables
                x = self._beta(rng, alpha, beta)
                customers.append(
                    {
                        "customer_id": f"cust_{merchant_idx:03d}_{cust_idx:04d}",
                        "merchant_id": merchant_id,
                        "creditworthiness": x,           # latent: 0.0–1.0
                        "payment_attempt_count": rng.randint(1, 50),
                        "successful_payment_count": 0,   # filled below
                    }
                )
        # Assign successful_payment_count correlated with creditworthiness
        for cust in customers:
            cw = float(cust["creditworthiness"])
            attempts = int(cust["payment_attempt_count"])
            success_rate = 0.2 + 0.7 * cw   # range: 0.2–0.9
            cust["successful_payment_count"] = max(
                0, round(attempts * success_rate + rng.gauss(0, 1))
            )
        return customers

    def _generate_case(
        self,
        index: int,
        rng: random.Random,
        customers: list[dict[str, object]],
    ) -> SyntheticCase:
        """Generate a single synthetic case."""
        # Pick a random customer from the pool
        customer = rng.choice(customers)
        merchant_id = str(customer["merchant_id"])
        customer_id = str(customer["customer_id"])
        creditworthiness = float(customer["creditworthiness"])

        # ---- Temporal: spread cases over _DATA_HORIZON_DAYS ----
        offset_seconds = rng.randint(0, _DATA_HORIZON_DAYS * 86400)
        created_at = _EPOCH - timedelta(seconds=offset_seconds)
        hour_of_day = created_at.hour
        day_of_week = created_at.weekday()  # 0=Monday, 6=Sunday

        # ---- Payment amount: log-normal distributed (realistic payment sizes) ----
        # Mode around ₹500 (50 000 paise), long tail for larger amounts
        log_amount = rng.gauss(10.8, 1.2)      # ln(50000) ≈ 10.82
        amount_paise = max(100, round(2.718281828 ** log_amount))

        # ---- Exposure tier (deterministic from amount) ----
        if amount_paise >= _EXPOSURE_HIGH_PAISE:
            exposure_tier = "HIGH"
        elif amount_paise >= _EXPOSURE_MEDIUM_PAISE:
            exposure_tier = "MEDIUM"
        else:
            exposure_tier = "LOW"

        # ---- Failure category: mixture modulated by creditworthiness ----
        failure_category = self._draw_failure_category(rng, creditworthiness)

        # ---- Payment method ----
        methods, weights = zip(*_PAYMENT_METHODS, strict=True)
        payment_method = rng.choices(list(methods), weights=list(weights), k=1)[0]

        # ---- Customer history ----
        payment_attempt_count = int(customer["payment_attempt_count"])
        successful_payment_count = int(customer["successful_payment_count"])
        has_subscription = rng.random() < 0.30   # 30% subscription payments

        # ---- IDs ----
        case_id = f"case_{index:08d}"
        payment_id = f"pay_{index:08d}"

        # ---- Recovery outcome: generated AFTER features, via independent draw ----
        # This is the ONLY place where recovery_outcome is computed.
        # It uses only latent variables and a fresh RNG draw — no feature column
        # is derived from this value, preventing label leakage.
        recovery_outcome = self._draw_recovery_outcome(
            rng,
            failure_category,
            creditworthiness,
            payment_attempt_count,
            exposure_tier,
        )

        return SyntheticCase(
            case_id=case_id,
            merchant_id=merchant_id,
            customer_id=customer_id,
            payment_id=payment_id,
            created_at=created_at,
            amount_paise=amount_paise,
            currency="INR",
            failure_category=failure_category,
            payment_method=payment_method,
            payment_attempt_count=payment_attempt_count,
            successful_payment_count=successful_payment_count,
            hour_of_day=hour_of_day,
            day_of_week=day_of_week,
            has_subscription=has_subscription,
            exposure_tier=exposure_tier,
            recovery_outcome=recovery_outcome,
        )

    def _draw_failure_category(
        self, rng: random.Random, creditworthiness: float
    ) -> str:
        """Draw a failure category whose distribution is modulated by creditworthiness.

        Customers with low creditworthiness have higher probability of
        INSUFFICIENT_FUNDS and CARD_DECLINED (structural payment difficulties).
        Customers with high creditworthiness have higher probability of
        TECHNICAL_FAILURE and NETWORK_TIMEOUT (transient, recoverable failures).
        """
        categories = list(_FAILURE_WEIGHTS.keys())
        base_weights = list(_FAILURE_WEIGHTS.values())

        # Creditworthiness adjustment: shift weight toward transient failures
        # for higher-creditworthiness customers.
        adjusted: list[float] = []
        for cat, w in zip(categories, base_weights, strict=True):
            if cat in ("INSUFFICIENT_FUNDS", "CARD_DECLINED", "FRAUD_SUSPECTED"):
                # Low-cw failures: reduced by creditworthiness
                adjusted.append(w * (1.0 - 0.5 * creditworthiness))
            elif cat in ("TECHNICAL_FAILURE", "NETWORK_TIMEOUT", "AUTHENTICATION_FAILURE"):
                # Transient failures: increased by creditworthiness
                adjusted.append(w * (1.0 + creditworthiness))
            else:
                adjusted.append(w)

        return rng.choices(categories, weights=adjusted, k=1)[0]

    def _draw_recovery_outcome(
        self,
        rng: random.Random,
        failure_category: str,
        creditworthiness: float,
        payment_attempt_count: int,
        exposure_tier: str,
    ) -> bool:
        """Compute the recovery outcome (target label).

        Formula:
            p = base_rate(failure_category)
              * creditworthiness_factor(creditworthiness)
              * attempt_factor(payment_attempt_count)
              * exposure_factor(exposure_tier)

        The outcome is then drawn as Bernoulli(p).

        CRITICAL: This function is called AFTER all features are computed.
        Its return value is NEVER used as an input to any feature column.
        This is the label leakage prevention guarantee (EVAL-008).
        """
        base_rate = _BASE_RECOVERY_RATE.get(failure_category, 0.25)

        # Creditworthiness factor: higher cw → more likely to resolve
        # Range: 0.5–1.5 (±50% adjustment)
        cw_factor = 0.5 + creditworthiness

        # Attempt count factor: too many attempts signals chronic issues
        # Range: 0.7–1.0 (penalty for high attempt counts)
        attempt_factor = max(0.7, 1.0 - 0.01 * payment_attempt_count)

        # Exposure factor: smaller amounts are easier to recover
        if exposure_tier == "LOW":
            exposure_factor = 1.2
        elif exposure_tier == "MEDIUM":
            exposure_factor = 1.0
        else:
            exposure_factor = 0.8

        prob = min(0.95, max(0.05, base_rate * cw_factor * attempt_factor * exposure_factor))

        return rng.random() < prob

    @staticmethod
    def _beta(rng: random.Random, alpha: float, beta: float) -> float:
        """Sample from a Beta(alpha, beta) distribution.

        Uses the ratio-of-Gammas method: Beta(a, b) = Gamma(a) / (Gamma(a) + Gamma(b)).
        Python's random.gammavariate implements the Gamma distribution.
        """
        x = rng.gammavariate(alpha, 1.0)
        y = rng.gammavariate(beta, 1.0)
        denom = x + y
        if denom == 0.0:
            return 0.5
        return x / denom


# ---------------------------------------------------------------------------
# Module-level convenience function
# ---------------------------------------------------------------------------


def generate(seed: int, count: int) -> list[SyntheticCase]:
    """Generate ``count`` synthetic cases with the given ``seed``.

    Convenience wrapper around ``SyntheticDataGenerator().generate()``.
    This is the canonical interface for the training pipeline (task 10.4)
    and for property-based tests (task 10.9 / Property 12).

    Parameters
    ----------
    seed:
        Integer random seed.  Same seed → identical output.
    count:
        Number of cases.  Must be >= 1.

    Returns
    -------
    list[SyntheticCase]
        Chronologically ordered cases (oldest first).

    Requirements: EVAL-005, EVAL-006
    """
    return SyntheticDataGenerator().generate(seed=seed, count=count)
